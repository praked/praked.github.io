"""Make web-sized WebP copies of the travel photos used on /misc/.

    python tools/optimize-travel-photos.py

Reads every .jpg in assets/img/travel/ (the originals are kept, their URLs
are part of tools/urls-baseline.txt) and writes, for each one,

    assets/img/travel-web/<name>-<width>.webp

only where that is a real downscale: a copy is made at a width only if the
original is at least DOWNSCALE times wider. Re-encoding a photo at (nearly)
its own size just adds a second round of compression artefacts for little
saving, so small originals are served as they are. The 240px thumbnail is
always made. Also writes _data/travel_sizes.yml, which tells
_includes/slider.html which widths exist; the original JPEG is always offered
as the largest candidate. Needs Pillow.
"""
import pathlib
from PIL import Image, ImageOps

SRC = pathlib.Path("assets/img/travel")
DST = pathlib.Path("assets/img/travel-web")
THUMB = 240
WIDTHS = (800, 1400)
DOWNSCALE = 1.25
QUALITY = 88        # photos; thumbnails use 80
DST.mkdir(exist_ok=True)

lines = ["# Generated by tools/optimize-travel-photos.py. Do not edit by hand.",
         "# <photo name>: { w: original width, h: original height, widths: [...] }"]
for f in sorted(SRC.glob("*.jpg"), key=lambda p: p.stem.lower()):
    im = ImageOps.exif_transpose(Image.open(f)).convert("RGB")
    made = []
    def save(ww, q):
        out = DST / f"{f.stem}-{ww}.webp"
        im.resize((ww, round(im.height * ww / im.width)), Image.Resampling.LANCZOS).save(out, "WEBP", quality=q, method=6)
        made.append(ww)
    save(min(THUMB, im.width), 80)
    for w in WIDTHS:
        if im.width >= w * DOWNSCALE:
            save(w, QUALITY)
    made = sorted(set(made))
    lines.append(f"{f.stem}: {{ w: {im.width}, h: {im.height}, widths: [{', '.join(map(str, made))}] }}")
    print(f.name, made)
pathlib.Path("_data/travel_sizes.yml").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
